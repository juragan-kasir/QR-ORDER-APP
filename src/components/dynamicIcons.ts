export function getDynamicIcon(name?: string | null): LucideIcon {
  if (!name) return Folder;
  const normalized = name.toLowerCase().trim().replace(/[-\s]+/g, "_");
  return ICON_MAP[normalized] || ICON_MAP[name] || Folder;
}

/** Nama ikon dikenal di peta FE-POS (selain itu dianggap teks/emoji). */
export function hasDynamicIcon(name: string): boolean {
  const normalized = name.toLowerCase().trim().replace(/[-\s]+/g, "_");
  return normalized in ICON_MAP;
}
